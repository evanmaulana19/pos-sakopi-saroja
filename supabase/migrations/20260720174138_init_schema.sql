-- Buat Tabel Profil Pengguna (Terkait dengan Supabase Auth)
CREATE TABLE users_profile (
  id UUID REFERENCES auth.users(id) PRIMARY KEY,
  email TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('kasir', 'admin', 'owner')),
  name TEXT NOT NULL
);

-- Buat Tabel Kategori Menu
CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL
);

-- Buat Tabel Produk/Menu
CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  price NUMERIC NOT NULL,
  image_url TEXT NOT NULL,
  is_available BOOLEAN DEFAULT TRUE NOT NULL
);

-- Buat Tabel Transaksi Induk
CREATE TABLE transactions (
  id UUID PRIMARY KEY,
  cashier_id UUID REFERENCES users_profile(id) ON DELETE SET NULL,
  total_amount NUMERIC NOT NULL,
  payment_method TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Selesai',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Buat Tabel Detail Item Transaksi
CREATE TABLE transaction_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id UUID REFERENCES transactions(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  quantity INTEGER NOT NULL,
  price_at_time NUMERIC NOT NULL
);

-- Buat Tabel Beban Pengeluaran (Expenses)
CREATE TABLE expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  amount NUMERIC NOT NULL,
  description TEXT NOT NULL,
  expense_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

