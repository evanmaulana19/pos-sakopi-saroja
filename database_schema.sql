-- Kebijakan Tabel expenses (Hanya Owner yang berhak melihat & mengelola pengeluaran keuangan):
CREATE POLICY "expenses_owner_only"
  ON public.expenses FOR ALL
  TO authenticated
  USING (public.get_my_role() = 'owner')
  WITH CHECK (public.get_my_role() = 'owner');

-- Kebijakan Tabel security_logs:
CREATE POLICY "security_logs_insert_all"
  ON public.security_logs FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

CREATE POLICY "security_logs_select_admin_owner"
  ON public.security_logs FOR SELECT
  TO authenticated
  USING (public.get_my_role() IN ('admin', 'owner'));

