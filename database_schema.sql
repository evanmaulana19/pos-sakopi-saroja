-- Kebijakan Tabel users_profile:
-- 1) User terautentikasi dapat melihat profil sendiri atau staf (untuk relasi nama kasir),
-- 2) User baru hanya bisa insert profil miliknya sendiri (id = auth.uid()) dengan role 'kasir' (atau Owner insert staf),
-- 3) Hanya 'owner' yang dapat mengubah role/profil staf lain (mencegah IDOR & Privilege Escalation).
CREATE POLICY "users_profile_select_authenticated"
  ON public.users_profile FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "users_profile_insert_self_or_owner"
  ON public.users_profile FOR INSERT
  TO authenticated
  WITH CHECK (
    (id = auth.uid() AND role = 'kasir')
    OR public.get_my_role() = 'owner'
  );

CREATE POLICY "users_profile_update_owner_only"
  ON public.users_profile FOR UPDATE
  TO authenticated
  USING (public.get_my_role() = 'owner')
  WITH CHECK (public.get_my_role() = 'owner');

CREATE POLICY "users_profile_delete_owner_only"
  ON public.users_profile FOR DELETE
  TO authenticated
  USING (public.get_my_role() = 'owner' AND id <> auth.uid());

-- Kebijakan Tabel categories:
CREATE POLICY "categories_select_authenticated"
  ON public.categories FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "categories_modify_admin_owner"
  ON public.categories FOR ALL
  TO authenticated
  USING (public.get_my_role() IN ('admin', 'owner'))
  WITH CHECK (public.get_my_role() IN ('admin', 'owner'));

