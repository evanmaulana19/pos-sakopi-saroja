-- 1. Buat Tabel Profil Pengguna (Terkait dengan Supabase Auth)
CREATE TABLE IF NOT EXISTS users_profile (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  email TEXT NOT NULL CHECK (char_length(email) <= 150),
  role TEXT NOT NULL DEFAULT 'kasir' CHECK (role IN ('kasir', 'admin', 'owner')),
  name TEXT NOT NULL CHECK (char_length(name) <= 100)
);

-- 2. Buat Tabel Kategori Menu
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(name) <= 80)
);

-- 3. Buat Tabel Produk/Menu
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  name TEXT NOT NULL CHECK (char_length(name) <= 100),
  price NUMERIC NOT NULL CHECK (price > 0),
  image_url TEXT NOT NULL,
  is_available BOOLEAN DEFAULT TRUE NOT NULL
);

-- 4. Buat Tabel Transaksi Induk
CREATE TABLE IF NOT EXISTS transactions (
  id UUID PRIMARY KEY,
  cashier_id UUID REFERENCES users_profile(id) ON DELETE SET NULL,
  total_amount NUMERIC NOT NULL CHECK (total_amount > 0),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('Tunai', 'Non-Tunai')),
  status TEXT NOT NULL DEFAULT 'Diproses' CHECK (status IN ('Diproses', 'Selesai')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Buat Tabel Detail Item Transaksi
CREATE TABLE IF NOT EXISTS transaction_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id UUID REFERENCES transactions(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  price_at_time NUMERIC NOT NULL CHECK (price_at_time >= 0)
);

-- 6. Buat Tabel Beban Pengeluaran (Expenses)
CREATE TABLE IF NOT EXISTS expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  amount NUMERIC NOT NULL CHECK (amount > 0),
  description TEXT NOT NULL CHECK (char_length(description) <= 150),
  expense_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. Buat Tabel Log Audit Keamanan (Security & Activity Logs)
CREATE TABLE IF NOT EXISTS security_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL,
  severity TEXT NOT NULL CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
  actor_email TEXT NOT NULL DEFAULT 'anonymous',
  description TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ============================================================================
-- TRIGGER OTOMATIS REGISTRASI USER (MENCEGAH PRIVILEGE ESCALATION)
-- ============================================================================
-- Setiap user baru yang mendaftar melalui Supabase Auth otomatis dibuatkan
-- profil dengan role standar 'kasir' (tidak bisa memalsukan role 'admin'/'owner').
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.users_profile (id, email, role, name)
  VALUES (
    NEW.id,
    NEW.email,
    'kasir',
    COALESCE(NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1))
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ============================================================================
-- FUNGSI HELPER OTORISASI PERAN (RBAC)
-- ============================================================================
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER SET search_path = public
AS $$
  SELECT role FROM public.users_profile WHERE id = auth.uid();
$$;

