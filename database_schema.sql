  ON public.transactions FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "transactions_insert_own_cashier_id"
  ON public.transactions FOR INSERT
  TO authenticated
  WITH CHECK (
    cashier_id = auth.uid()
    AND public.get_my_role() IN ('kasir', 'admin', 'owner')
  );

CREATE POLICY "transactions_update_authenticated"
  ON public.transactions FOR UPDATE
  TO authenticated
  USING (public.get_my_role() IN ('kasir', 'admin', 'owner'))
  WITH CHECK (public.get_my_role() IN ('kasir', 'admin', 'owner'));

CREATE POLICY "transactions_delete_owner_only"
  ON public.transactions FOR DELETE
  TO authenticated
  USING (public.get_my_role() = 'owner');

-- Kebijakan Tabel transaction_items:
CREATE POLICY "transaction_items_select_authenticated"
